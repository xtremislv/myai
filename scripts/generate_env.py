"""Create the server's .env with new random secrets. Standard library only, so it can run
before anything is installed:

    python3 scripts/generate_env.py --model <hf-repo-id> --domain chat.example.com \\
        --grafana-domain ops.example.com

It refuses to overwrite an existing .env: replacing these secrets on a running system
would lock the database and vault out.
"""
from __future__ import annotations

import argparse
import base64
import os
import secrets
import sys
from pathlib import Path


def _token() -> str:
    return secrets.token_urlsafe(32)


def write_env(path: Path, args: argparse.Namespace) -> None:
    postgres_password = _token()
    content = f"""# Generated by scripts/generate_env.py. Keep a copy somewhere safe and off this server:
# backups do not include this file, and VAULT_MASTER_KEY can't be recovered.
ENVIRONMENT=production

# Model
LLM_MODEL={args.model}
LLM_BASE_URL=http://vllm:8001/v1
HUGGING_FACE_HUB_TOKEN={args.hf_token}
VLLM_MAX_MODEL_LEN=8192
VLLM_GPU_UTIL=0.90
# Depends on the card and the weights. See docs/SERVER_SETUP.md, step 5.
VLLM_EXTRA_ARGS={args.vllm_args}

# Web addresses, used by the Caddy proxy
DOMAIN={args.domain}
GRAFANA_DOMAIN={args.grafana_domain}

# Secrets
JWT_SECRET={secrets.token_urlsafe(48)}
VAULT_MASTER_KEY={base64.b64encode(os.urandom(32)).decode()}
GRAFANA_PASSWORD={_token()}

# Postgres
POSTGRES_PASSWORD={postgres_password}
POSTGRES_DSN=postgresql://ai:{postgres_password}@postgres:5432/ai_platform

# Redis
REDIS_URL=redis://redis:6379/0

# MinIO
MINIO_ENDPOINT=minio:9000
MINIO_ACCESS_KEY=ai-platform
MINIO_SECRET_KEY={_token()}
MINIO_BUCKET=ai-platform
MINIO_SECURE=false

# Backups. An rclone destination such as myremote:ai-platform-backups. Leave it empty and
# backups stay on this server, which can be wiped when the instance is terminated.
BACKUP_DEST={args.backup_dest}
BACKUP_KEEP_DAYS=7

# Observability
OTEL_EXPORTER_OTLP_ENDPOINT=http://otel-collector:4317
OTEL_SERVICE_NAME=ai-platform-gateway
"""
    path.write_text(content)
    path.chmod(0o600)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--model", required=True, help="exact Hugging Face repo id, like org/model-name")
    parser.add_argument("--domain", required=True, help="web address for the app")
    parser.add_argument("--grafana-domain", required=True, help="web address for Grafana")
    parser.add_argument("--hf-token", default="", help="only needed if the model is gated")
    parser.add_argument("--vllm-args", default="", help='extra vLLM flags, like "--quantization awq"')
    parser.add_argument("--backup-dest", default="", help="rclone destination for backups")
    parser.add_argument("--path", default=".env")
    args = parser.parse_args(argv)

    path = Path(args.path)
    if path.exists():
        sys.exit(f"{path} already exists. Replacing its secrets would lock the system out of its own data.")
    write_env(path, args)
    print(f"Wrote {path}. Save a copy off this server now: it can't be recovered.")


if __name__ == "__main__":
    main()
